export function findDepartment(id: DepartmentId) {
  return departments.find((item) => item.id === id) ?? null;
}

export function splitCourseLabel(label: string) {
  const match = label.match(/^([A-Za-zÇĞİÖŞÜçğıöşü0-9]+\s+\d+)\s+(.+)$/);
  if (!match) return { code: '', name: label };
  return { code: match[1], name: match[2] };
}
